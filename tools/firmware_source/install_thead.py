"""Add bounded RV32 T-Head semantics to a workspace-local Ghidra installation.
Encodings: LLVM 19.1.7 RISCVInstrInfoXTHead.td; see README for limitations.
"""
from pathlib import Path
import argparse


def specification():
    out = ['# NanoCore RV32 T-Head / legacy P subset. Generated by install_thead.py.',
        'attach variables [nc_dhi nc_shi nc_thi] [ra gp t0 t2 s1 a1 a3 a5 a7 s3 s5 s7 s9 s11 t4 t6];']
    def ins(name, operands, match, body):
        out.append(f':{name} {operands} is op0006=0x0b & {match} {{ {body} }}')
    ins('th.addsl','rd,rs1,rs2,op2526','op1214=1 & op2731=0 & rd & rs1 & rs2 & op2526','rd = rs1 + (rs2 << op2526);')
    for name, code, shift in [('th.ext',2,'s>>'),('th.extu',3,'>>')]:
        ins(name,'rd,rs1,op2631,op2025',f'op1214={code} & op3131=0 & op2525=0 & rd & rs1 & op2631 & op2025',f'local left:4 = 31 - op2631; local right:4 = left + op2025; rd = (rs1 << left) {shift} right;')
    for name, code, condition in [('th.mveqz',32,'!='),('th.mvnez',33,'==')]:
        ins(name,'rd,rs1,rs2',f'op1214=1 & op2531={code} & rd & rs1 & rs2',f'if (rs2 {condition} 0) goto <done>; rd = rs1; <done>')
    for name, code, sign in [('th.mula',16,'+'),('th.muls',17,'-')]:
        ins(name,'rd,rs1,rs2',f'op1214=1 & op2531={code} & rd & rs1 & rs2',f'rd = rd {sign} (rs1 * rs2);')
    for suffix, code, size, extension in [('b',0,1,'sext'),('bu',16,1,'zext'),('h',4,2,'sext'),('hu',20,2,'zext'),('w',8,4,'')]:
        val=f'*:4 ea' if size==4 else f'{extension}(*:{size} ea)'
        ins('th.lr'+suffix,'rd,rs1,rs2,op2526',f'op1214=4 & op2731={code} & rd & rs1 & rs2 & op2526',f'local ea:4 = rs1 + (rs2 << op2526); rd = {val};')
        # ia = use old base then update; ib = update before access.
        for after, delta in [(True,3),(False,1)]:
            name='th.l'+suffix+('ia' if after else 'ib')
            addr='r1519' if after else 'next'
            val=f'*:4 ea' if size==4 else f'{extension}(*:{size} ea)'
            ins(name,'rd,r1519,op2024,op2526',f'op1214=4 & op2731={code+delta} & rd & r1519 & op2024 & op2526',f'local imm:4 = op2024; imm = (imm << 27) s>> 27; local next:4 = r1519 + (imm << op2526); local ea:4 = {addr}; rd = {val}; r1519 = next;')
    for suffix,code,size in [('b',0,1),('h',4,2),('w',8,4)]:
        value='rd' if size==4 else f'rd:{size}'
        ins('th.sr'+suffix,'rd,rs1,rs2,op2526',f'op1214=5 & op2731={code} & rd & rs1 & rs2 & op2526',f'local ea:4 = rs1 + (rs2 << op2526); *:{size} ea = {value};')
        for after,delta in [(True,3),(False,1)]:
            addr='r1519' if after else 'next'
            ins('th.s'+suffix+('ia' if after else 'ib'),'rd,r1519,op2024,op2526',f'op1214=5 & op2731={code+delta} & rd & r1519 & op2024 & op2526',f'local imm:4 = op2024; imm = (imm << 27) s>> 27; local next:4 = r1519 + (imm << op2526); local ea:4 = {addr}; *:{size} ea = {value}; r1519 = next;')
    # Legacy P v0.9.x encodings from the SDK's Xuantie 2.6.1 binutils.
    def pins(name, operands, match, body):
        out.append(f':{name} {operands} is op0006=0x77 & {match} {{ {body} }}')
    for name,code,operation in [('add64',0x60,'+'),('sub64',0x61,'-')]:
        pins(name,'rd,rs1,rs2',f'op1214=1 & op2531={code} & op0707=0 & nc_sodd=0 & op2020=0 & rd & rs1 & rs2 & nc_dhi & nc_shi & nc_thi',
             f'local a:8 = (zext(nc_shi) << 32) | zext(rs1); local b:8 = (zext(nc_thi) << 32) | zext(rs2); local v:8 = a {operation} b; rd = v:4; local high:8 = v >> 32; nc_dhi = high:4;')
    for name,code,ext,accumulate in [('mulr64',0x78,'zext',False),('smar64',0x42,'sext',True),('umar64',0x52,'zext',True)]:
        acc='local acc:8 = (zext(nc_dhi) << 32) | zext(rd); v = v + acc;' if accumulate else ''
        pins(name,'rd,rs1,rs2',f'op1214=1 & op2531={code} & op0707=0 & rd & rs1 & rs2 & nc_dhi',
             f'local a:8 = {ext}(rs1); local b:8 = {ext}(rs2); local v:8 = a * b; {acc} rd = v:4; local high:8 = v >> 32; nc_dhi = high:4;')
    pins('wexti','rd,rs1,op2024','op1214=0 & op2531=0x6f & nc_sodd=0 & rd & rs1 & nc_shi & op2024',
         'local v:8 = (zext(nc_shi) << 32) | zext(rs1); v = v >> op2024; rd = v:4;')
    pins('insb','rd,rs1,nc_bpos','op1214=0 & op2531=0x56 & nc_ins_reserved=0 & rd & rs1 & nc_bpos',
         'local shift:4 = nc_bpos * 8; local mask:4 = 0xff << shift; rd = (rd & ~mask) | ((rs1 & 0xff) << shift);')
    for name,code,expr in [('pkbb16',7,'(rs1 << 16) | (rs2 & 0xffff)'),('pktb16',31,'(rs1 & 0xffff0000) | (rs2 & 0xffff)')]:
        pins(name,'rd,rs1,rs2',f'op1214=1 & op2531={code} & rd & rs1 & rs2',f'rd = {expr};')
    for name,code,cond in [('minw',0x78,'s<'),('maxw',0x79,'s>')]:
        pins(name,'rd,rs1,rs2',f'op1214=0 & op2531={code} & rd & rs1 & rs2',f'local a:4 = rs1; local b:4 = rs2; if (a {cond} b) goto <first>; rd = b; goto <end>; <first> rd = a; <end>')
    pins('swap8','rd,rs1','op1214=0 & op2031=0xad8 & rd & rs1',
         'rd = ((rs1 & 0x00ff00ff) << 8) | ((rs1 & 0xff00ff00) >> 8);')
    ins('th.fmv.x.hw','rd,frs1','op1214=1 & op2031=0xc00 & rd & frs1', 'local high:8 = frs1 >> 32; rd = high:4;')
    ins('th.fmv.hw.x','frd,rs1','op1214=1 & op2031=0xa00 & frd & rs1', 'frd = (frd & 0xffffffff) | (zext(rs1) << 32);')
    return '\n\n'.join(out)+'\n'


def main():
    p=argparse.ArgumentParser();p.add_argument('ghidra',type=Path);a=p.parse_args()
    lang=a.ghidra/'Ghidra/Processors/RISCV/data/languages'
    registers=lang/'riscv.reg.sinc'
    regtext=registers.read_text()
    if 'nc_dhi=' not in regtext:
        registers.with_suffix('.sinc.nanocore-original').write_text(regtext)
        regtext=regtext.replace('define token instr (32)', 'define token instr (32)\n  nc_dhi=(8,11) nc_shi=(16,19) nc_thi=(21,24) nc_sodd=(15,15) nc_bpos=(20,21) nc_ins_reserved=(22,24)')
        registers.write_text(regtext)
    target=lang/'riscv.ilp32d.slaspec'
    original=target.read_text();backup=target.with_suffix('.slaspec.nanocore-original')
    if not backup.exists():backup.write_text(original)
    (lang/'nanocore-thead.sinc').write_text(specification())
    include='@include "nanocore-thead.sinc"'
    if include not in original:target.write_text(original+'\n'+include+'\n')

if __name__=='__main__':main()
